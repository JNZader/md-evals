"""Pipeline evaluation engine for md-evals.

Provides a multi-stage evaluation pipeline with probes, detectors, and model
routing.  The pipeline executes stages sequentially —
PreCheck → Auditor → Target → Judge — passing a mutable ``EvalContext``
through each stage and producing a single ``EvalResult``.

Public API
----------
Protocols
    ``PipelineStage``, ``Probe``, ``Detector`` — structural interfaces
    (``typing.Protocol``) for stages, scenario generators, and response
    scorers.  Implement the shape and you satisfy the contract — no
    inheritance required.

Data
    ``EvalContext`` — mutable state threaded through stages.
    ``Scenario`` — frozen test scenario generated by a probe.
    ``StageResult`` — frozen outcome of a single stage execution.
    ``StageError`` — frozen error record captured during pipeline execution.

Orchestration
    ``Pipeline`` — sequential stage executor with per-stage timeouts and
    graceful degradation.

Configuration
    ``PipelineConfig``, ``AuditorConfig``, ``TargetConfig``, ``JudgeConfig``
    — Pydantic models for YAML-driven pipeline configuration.

Skill Parsing
    ``ParsedSkill``, ``SkillParser`` — parse ``SKILL.md`` files into a
    structured representation used by probes and the auditor stage.
"""

